/**
 * ホーくんの まめちしき。
 *
 * タイトルの フクロウを押すと、にがてな式のかわりに ときどきこれが出る。
 * ねらいは「数のことを聞くのが たのしい」に寄せること。
 * 式だけを出しつづけると、押すこと自体が れんしゅうの合図になってしまい、
 * 3日めには押されなくなる。**当たりが2種類あるから、もう一度押す。**
 *
 * 中身のきまり:
 * - **かならず数の話にする。** 動物や身のまわりの話でも、行きつく先は数にする
 * - **こたえは短く。** ふきだしでいちばん大きい字になるので、10文字を超えない
 * - **ひらがな・カタカナだけ。** 6さいが一人で読める字にそろえる
 * - **1つは1画面。** 読みきれない長さは、ふきだしがボタンの上まで伸びてしまう
 *
 * 記録（★・ずかん・習熟度）は、ここからは一切さわらない。
 */

