/**
 * まだ出していないものから1つ。
 * 毎回ばらばらに引くと同じ話が続けて出るので、**ぜんぶ出しきってから**混ぜなおす。
 * 34こ あるので、1日に何回押しても おなじ話には まず当たらない。
 */
let deck: Trivia[] = [];
let at = 0;

export function nextTrivia(): Trivia {
  if (at >= deck.length) {
    deck = LIST.slice();
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
    at = 0;
  }
  return deck[at++];
}
